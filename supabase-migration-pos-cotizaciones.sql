-- Cotizaciones del POS: se guardan sin afectar inventario ni registrar pagos.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pos_cotizaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero text UNIQUE,
  estado text NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','vendida','cancelada')),
  cliente jsonb NOT NULL DEFAULT '{}'::jsonb,
  nivel_precio text CHECK (nivel_precio IS NULL OR nivel_precio IN ('A','B','C','D','E')),
  items jsonb NOT NULL CHECK (jsonb_typeof(items)='array' AND jsonb_array_length(items)>0),
  entrega jsonb NOT NULL DEFAULT '{}'::jsonb,
  observacion text,
  subtotal numeric(14,2) NOT NULL CHECK (subtotal>=0),
  venta_id bigint REFERENCES public.pos_ventas(id),
  vendedor uuid NOT NULL DEFAULT auth.uid(),
  creada_en timestamptz NOT NULL DEFAULT now(),
  actualizada_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pos_cotizaciones_pendientes_fecha
  ON public.pos_cotizaciones (creada_en DESC) WHERE estado='pendiente';

ALTER TABLE public.pos_cotizaciones ENABLE ROW LEVEL SECURITY;
