GRANT SELECT ON public.pos_cotizaciones TO authenticated;

CREATE OR REPLACE FUNCTION public.pos_guardar_cotizacion(p_cotizacion jsonb,p_id bigint DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_items jsonb:=COALESCE(p_cotizacion->'items','[]'::jsonb);
  v_total numeric(14,2);
  v_estado text;
  v_result jsonb;
  v_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF jsonb_typeof(v_items)<>'array' OR jsonb_array_length(v_items)=0 THEN RAISE EXCEPTION 'Agrega productos a la cotización'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_items) x
    WHERE COALESCE(NULLIF(x->>'producto_id','')::bigint,0)<=0
       OR COALESCE(NULLIF(x->>'cantidad','')::integer,0)<=0
       OR COALESCE(NULLIF(x->>'precio_unitario','')::numeric,-1)<0
  ) THEN RAISE EXCEPTION 'Revisa productos, cantidades y precios de la cotización'; END IF;
  SELECT COALESCE(sum((x->>'cantidad')::numeric*(x->>'precio_unitario')::numeric),0)
    INTO v_total FROM jsonb_array_elements(v_items) x;
  IF p_id IS NULL THEN
    INSERT INTO public.pos_cotizaciones(cliente,nivel_precio,items,entrega,observacion,subtotal)
      VALUES(COALESCE(p_cotizacion->'cliente','{}'::jsonb),NULLIF(p_cotizacion->>'nivel_precio',''),v_items,
        COALESCE(p_cotizacion->'entrega','{}'::jsonb),NULLIF(btrim(p_cotizacion->>'observacion'),''),v_total)
      RETURNING id INTO v_id;
    UPDATE public.pos_cotizaciones SET numero='COT-'||lpad(v_id::text,6,'0') WHERE id=v_id;
  ELSE
    SELECT estado INTO v_estado FROM public.pos_cotizaciones WHERE id=p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Cotización no encontrada'; END IF;
    IF v_estado<>'pendiente' THEN RAISE EXCEPTION 'Solo se pueden modificar cotizaciones pendientes'; END IF;
    v_id:=p_id;
    UPDATE public.pos_cotizaciones SET cliente=COALESCE(p_cotizacion->'cliente','{}'::jsonb),
      nivel_precio=NULLIF(p_cotizacion->>'nivel_precio',''),items=v_items,
      entrega=COALESCE(p_cotizacion->'entrega','{}'::jsonb),
      observacion=NULLIF(btrim(p_cotizacion->>'observacion'),''),subtotal=v_total,actualizada_en=now()
      WHERE id=v_id;
  END IF;
  SELECT to_jsonb(c) INTO v_result FROM public.pos_cotizaciones c WHERE c.id=v_id;
  RETURN v_result;
END $$;

CREATE OR REPLACE FUNCTION public.pos_marcar_cotizacion_vendida(p_cotizacion_id bigint,p_venta_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_estado text; v_result jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.pos_ventas WHERE id=p_venta_id) THEN RAISE EXCEPTION 'Venta no encontrada'; END IF;
  SELECT estado INTO v_estado FROM public.pos_cotizaciones WHERE id=p_cotizacion_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Cotización no encontrada'; END IF;
  IF v_estado='vendida' AND EXISTS(SELECT 1 FROM public.pos_cotizaciones WHERE id=p_cotizacion_id AND venta_id=p_venta_id) THEN
    SELECT to_jsonb(c) INTO v_result FROM public.pos_cotizaciones c WHERE c.id=p_cotizacion_id; RETURN v_result;
  END IF;
  IF v_estado<>'pendiente' THEN RAISE EXCEPTION 'La cotización ya no está pendiente'; END IF;
  UPDATE public.pos_cotizaciones SET estado='vendida',venta_id=p_venta_id,actualizada_en=now() WHERE id=p_cotizacion_id;
  SELECT to_jsonb(c) INTO v_result FROM public.pos_cotizaciones c WHERE c.id=p_cotizacion_id;
  RETURN v_result;
END $$;

CREATE OR REPLACE FUNCTION public.pos_cancelar_cotizacion(p_cotizacion_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_result jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  UPDATE public.pos_cotizaciones SET estado='cancelada',actualizada_en=now()
    WHERE id=p_cotizacion_id AND estado='pendiente';
  IF NOT FOUND THEN RAISE EXCEPTION 'Cotización pendiente no encontrada'; END IF;
  SELECT to_jsonb(c) INTO v_result FROM public.pos_cotizaciones c WHERE c.id=p_cotizacion_id;
  RETURN v_result;
END $$;

REVOKE ALL ON FUNCTION public.pos_guardar_cotizacion(jsonb,bigint),public.pos_marcar_cotizacion_vendida(bigint,bigint),public.pos_cancelar_cotizacion(bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.pos_guardar_cotizacion(jsonb,bigint),public.pos_marcar_cotizacion_vendida(bigint,bigint),public.pos_cancelar_cotizacion(bigint) TO authenticated;
COMMIT;
