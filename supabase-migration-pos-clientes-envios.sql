  IF NULLIF(btrim(p_cliente->>'nombre'),'') IS NULL OR (v_doc IS NULL AND v_tel IS NULL) THEN RAISE EXCEPTION 'Indica nombre y cédula o teléfono del cliente'; END IF;
  IF p_medio='transferencia' AND (NULLIF(btrim(p_banco),'') IS NULL OR NULLIF(btrim(p_referencia),'') IS NULL) THEN RAISE EXCEPTION 'Para una transferencia indica banco y referencia'; END IF;
  IF v_doc IS NOT NULL THEN
    INSERT INTO public.pos_clientes(nombre,documento,telefono,ciudad,barrio,direccion,nivel_precio,actualizado_en)
    VALUES(NULLIF(btrim(p_cliente->>'nombre'),''),v_doc,NULLIF(btrim(p_cliente->>'telefono'),''),NULLIF(btrim(p_cliente->>'ciudad'),''),NULLIF(btrim(p_cliente->>'barrio'),''),NULLIF(btrim(p_cliente->>'direccion'),''),NULLIF(p_cliente->>'nivel_precio',''),now())
    ON CONFLICT(documento) DO UPDATE SET nombre=EXCLUDED.nombre,telefono=COALESCE(EXCLUDED.telefono,pos_clientes.telefono),ciudad=COALESCE(EXCLUDED.ciudad,pos_clientes.ciudad),barrio=COALESCE(EXCLUDED.barrio,pos_clientes.barrio),direccion=COALESCE(EXCLUDED.direccion,pos_clientes.direccion),nivel_precio=COALESCE(EXCLUDED.nivel_precio,pos_clientes.nivel_precio),actualizado_en=now()
    RETURNING id INTO v_cliente_id;
  ELSE
    SELECT id INTO v_cliente_id FROM public.pos_clientes WHERE regexp_replace(COALESCE(telefono,''),'[^0-9]','','g') IN (v_tel,'57'||v_tel) ORDER BY actualizado_en DESC LIMIT 1 FOR UPDATE;
    IF v_cliente_id IS NULL THEN
      INSERT INTO public.pos_clientes(nombre,telefono,ciudad,barrio,direccion,nivel_precio) VALUES(NULLIF(btrim(p_cliente->>'nombre'),''),NULLIF(btrim(p_cliente->>'telefono'),''),NULLIF(btrim(p_cliente->>'ciudad'),''),NULLIF(btrim(p_cliente->>'barrio'),''),NULLIF(btrim(p_cliente->>'direccion'),''),NULLIF(p_cliente->>'nivel_precio','')) RETURNING id INTO v_cliente_id;
    ELSE
      UPDATE public.pos_clientes SET nombre=NULLIF(btrim(p_cliente->>'nombre'),''),telefono=COALESCE(NULLIF(btrim(p_cliente->>'telefono'),''),telefono),actualizado_en=now() WHERE id=v_cliente_id;
    END IF;
  END IF;
  INSERT INTO public.pos_movimientos_cuenta_cliente(cliente_id,tipo,monto,medio,banco,referencia_pago,nota)
  VALUES(v_cliente_id,'abono',p_monto,p_medio,NULLIF(btrim(p_banco),''),NULLIF(btrim(p_referencia),''),NULLIF(btrim(p_nota),''));
  IF p_medio='efectivo' THEN
    SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
    IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja antes de registrar un abono en efectivo'; END IF;
    INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,nota) VALUES(v_caja_id,'abono_cliente','ingreso',p_monto,'Abono de cliente: '||btrim(p_cliente->>'nombre'));
  END IF;
  RETURN public.pos_obtener_cuenta_cliente(v_doc,v_tel);
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_venta_en_caja()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_caja_id bigint;
BEGIN
  IF NEW.medio<>'efectivo' THEN RETURN NEW; END IF;
  SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
  IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja antes de registrar una venta en efectivo'; END IF;
  INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,venta_id,nota)
  VALUES(v_caja_id,'venta','ingreso',NEW.valor,NEW.venta_id,'Venta en efectivo');
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS pos_pago_efectivo_a_caja ON public.pos_pagos;
CREATE TRIGGER pos_pago_efectivo_a_caja AFTER INSERT ON public.pos_pagos FOR EACH ROW EXECUTE FUNCTION public.pos_registrar_venta_en_caja();

