CREATE OR REPLACE FUNCTION public.pos_obtener_cuenta_cliente(p_documento text DEFAULT NULL,p_telefono text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_cliente public.pos_clientes%ROWTYPE; v_credito numeric(14,2); v_deuda numeric(14,2); v_doc text; v_tel text; v_movimientos jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  v_doc:=regexp_replace(COALESCE(p_documento,''),'[^0-9]','','g');v_tel:=regexp_replace(COALESCE(p_telefono,''),'[^0-9]','','g');IF length(v_tel)=12 AND left(v_tel,2)='57' THEN v_tel:=substr(v_tel,3);END IF;
  SELECT * INTO v_cliente FROM public.pos_clientes c
  WHERE (v_doc<>'' AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc)
     OR (v_tel<>'' AND regexp_replace(COALESCE(c.telefono,''),'[^0-9]','','g') IN (v_tel,'57'||v_tel))
  ORDER BY CASE WHEN v_doc<>'' AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc THEN 0 ELSE 1 END,c.actualizado_en DESC LIMIT 1;
  IF NOT FOUND THEN RETURN jsonb_build_object('encontrado',false,'saldo_favor',0,'saldo_pendiente',0,'movimientos','[]'::jsonb); END IF;
  SELECT COALESCE(sum(CASE WHEN tipo='abono' THEN monto WHEN tipo='uso_abono' THEN -monto ELSE 0 END),0),
         COALESCE(sum(CASE WHEN tipo='deuda' THEN monto WHEN tipo='pago_deuda' THEN -monto ELSE 0 END),0)
  INTO v_credito,v_deuda FROM public.pos_movimientos_cuenta_cliente WHERE cliente_id=v_cliente.id;
  SELECT COALESCE(jsonb_agg(jsonb_build_object('tipo',tipo,'monto',monto,'medio',medio,'banco',banco,'referencia_pago',referencia_pago,'venta_id',venta_id,'nota',nota,'creado_en',creado_en) ORDER BY creado_en DESC),'[]'::jsonb)
  INTO v_movimientos FROM (SELECT * FROM public.pos_movimientos_cuenta_cliente WHERE cliente_id=v_cliente.id ORDER BY creado_en DESC LIMIT 20) recent;
  RETURN jsonb_build_object('encontrado',true,'cliente_id',v_cliente.id,'nombre',v_cliente.nombre,'documento',v_cliente.documento,'telefono',v_cliente.telefono,'saldo_favor',v_credito,'saldo_pendiente',v_deuda,'movimientos',v_movimientos);
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_venta_detallada(
  p_items jsonb, p_pagos jsonb, p_cliente jsonb DEFAULT '{}'::jsonb,
  p_nivel_precio text DEFAULT NULL, p_observacion text DEFAULT NULL,
  p_entrega jsonb DEFAULT '{}'::jsonb
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_result jsonb; v_id bigint; v_tipo text; v_transportadora text; v_pagos jsonb:=COALESCE(p_pagos,'[]'::jsonb); v_cliente_id bigint; v_doc text; v_tel text; v_total numeric(14,2); v_pagado numeric(14,2); v_credito numeric(14,2); v_aplicado numeric(14,2);
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  v_tipo:=COALESCE(NULLIF(p_entrega->>'tipo',''),'recoge_cliente');
  v_transportadora:=NULLIF(btrim(p_entrega->>'transportadora'),'');
  IF v_tipo NOT IN ('recoge_cliente','transportadora','domicilio') THEN RAISE EXCEPTION 'Tipo de entrega inválido'; END IF;
  IF v_tipo='transportadora' AND v_transportadora IS NULL THEN RAISE EXCEPTION 'Selecciona la transportadora'; END IF;
  SELECT COALESCE(sum((x->>'cantidad')::numeric*(x->>'precio_unitario')::numeric),0) INTO v_total FROM jsonb_array_elements(COALESCE(p_items,'[]'::jsonb)) x;
  SELECT COALESCE(sum((x->>'valor')::numeric),0) INTO v_pagado FROM jsonb_array_elements(v_pagos) x;
  v_doc:=NULLIF(regexp_replace(COALESCE(p_cliente->>'documento',''),'[^0-9]','','g'),'');v_tel:=NULLIF(regexp_replace(COALESCE(p_cliente->>'telefono',''),'[^0-9]','','g'),'');IF length(v_tel)=12 AND left(v_tel,2)='57' THEN v_tel:=substr(v_tel,3);END IF;
  SELECT id INTO v_cliente_id FROM public.pos_clientes c
  WHERE (v_doc IS NOT NULL AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc) OR (v_doc IS NULL AND v_tel IS NOT NULL AND regexp_replace(COALESCE(c.telefono,''),'[^0-9]','','g') IN (v_tel,'57'||v_tel))
  ORDER BY CASE WHEN v_doc IS NOT NULL AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc THEN 0 ELSE 1 END,c.actualizado_en DESC LIMIT 1 FOR UPDATE;
  IF v_cliente_id IS NOT NULL THEN
    SELECT COALESCE(sum(CASE WHEN tipo='abono' THEN monto WHEN tipo='uso_abono' THEN -monto ELSE 0 END),0) INTO v_credito FROM public.pos_movimientos_cuenta_cliente WHERE cliente_id=v_cliente_id;
  ELSE v_credito:=0; END IF;
  v_aplicado:=LEAST(GREATEST(v_total-v_pagado,0),GREATEST(v_credito,0));
  IF v_aplicado>0 THEN v_pagos:=v_pagos||jsonb_build_array(jsonb_build_object('medio','otro','valor',v_aplicado,'referencia_pago','__POS_SALDO_FAVOR__')); END IF;
  v_result:=public.pos_registrar_venta(p_items,v_pagos,p_cliente,p_nivel_precio,p_observacion);
  v_id:=(v_result->>'id')::bigint;
  IF v_aplicado>0 AND v_cliente_id IS NOT NULL THEN
    UPDATE public.pos_pagos SET medio='saldo_favor',referencia_pago=NULL WHERE venta_id=v_id AND medio='otro' AND referencia_pago='__POS_SALDO_FAVOR__';
    INSERT INTO public.pos_movimientos_cuenta_cliente(cliente_id,tipo,monto,venta_id,nota) VALUES(v_cliente_id,'uso_abono',v_aplicado,v_id,'Aplicado a venta '||v_id);
  END IF;
  UPDATE public.pos_ventas SET
    barrio=COALESCE(NULLIF(btrim(p_cliente->>'barrio'),''),barrio),
    direccion=COALESCE(NULLIF(btrim(p_cliente->>'direccion'),''),direccion),
    tipo_entrega=v_tipo,
    transportadora=CASE WHEN v_tipo='transportadora' THEN v_transportadora ELSE NULL END,
    numero_guia=CASE WHEN v_tipo='transportadora' THEN NULLIF(btrim(p_entrega->>'guia'),'') ELSE NULL END
  WHERE id=v_id;
  UPDATE public.pos_clientes SET
    barrio=COALESCE(NULLIF(btrim(p_cliente->>'barrio'),''),barrio),
    direccion=COALESCE(NULLIF(btrim(p_cliente->>'direccion'),''),direccion),
    actualizado_en=now()
  WHERE id=(SELECT cliente_id FROM public.pos_ventas WHERE id=v_id);
  RETURN v_result||jsonb_build_object('saldo_aplicado',v_aplicado,'saldo_favor_restante',GREATEST(v_credito-v_aplicado,0));
END $$;

