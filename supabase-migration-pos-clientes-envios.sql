  INSERT INTO public.pos_cajas(saldo_inicial) VALUES(p_saldo_inicial) RETURNING id INTO v_id;
  IF p_saldo_inicial>0 THEN INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,nota) VALUES(v_id,'apertura','ingreso',p_saldo_inicial,'Efectivo inicial'); END IF;
  RETURN public.pos_estado_caja();
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_movimiento_caja(p_tipo text,p_monto numeric,p_nota text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
