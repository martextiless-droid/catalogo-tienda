CREATE OR REPLACE FUNCTION public.pos_registrar_abono(p_cliente jsonb,p_monto numeric,p_medio text,p_banco text DEFAULT NULL,p_referencia text DEFAULT NULL,p_nota text DEFAULT NULL)
