CREATE OR REPLACE FUNCTION public.pos_estado_caja()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_caja public.pos_cajas%ROWTYPE; v_esperado numeric(14,2); v_movimientos jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  SELECT * INTO v_caja FROM public.pos_cajas ORDER BY id DESC LIMIT 1;
  IF NOT FOUND THEN RETURN jsonb_build_object('abierta',false,'tiene_caja',false,'movimientos','[]'::jsonb); END IF;
  SELECT v_caja.saldo_inicial+COALESCE(sum(CASE WHEN direccion='ingreso' THEN monto ELSE -monto END),0)
  INTO v_esperado FROM public.pos_movimientos_caja WHERE caja_id=v_caja.id AND tipo<>'apertura';
  SELECT COALESCE(jsonb_agg(jsonb_build_object('tipo',tipo,'direccion',direccion,'monto',monto,'nota',nota,'creado_en',creado_en,'venta_id',venta_id) ORDER BY creado_en DESC),'[]'::jsonb)
  INTO v_movimientos FROM public.pos_movimientos_caja WHERE caja_id=v_caja.id;
  RETURN jsonb_build_object('abierta',v_caja.estado='abierta','tiene_caja',true,'id',v_caja.id,'saldo_inicial',v_caja.saldo_inicial,'esperado',v_esperado,'abierta_en',v_caja.abierta_en,'cerrada_en',v_caja.cerrada_en,'efectivo_contado',v_caja.efectivo_contado,'diferencia',v_caja.diferencia,'movimientos',v_movimientos);
END $$;

CREATE OR REPLACE FUNCTION public.pos_abrir_caja(p_saldo_inicial numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_saldo_inicial IS NULL OR p_saldo_inicial<0 THEN RAISE EXCEPTION 'El efectivo inicial debe ser cero o mayor'; END IF;
