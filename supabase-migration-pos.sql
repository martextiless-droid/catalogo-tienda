CREATE OR REPLACE FUNCTION public.pos_guardar_config_producto(p_producto_id bigint, p_codigo_barras text DEFAULT NULL, p_costo numeric DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_costo IS NULL OR p_costo<0 THEN RAISE EXCEPTION 'El costo no puede ser negativo'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.productos WHERE id=p_producto_id AND COALESCE(eliminado,false)=false) THEN RAISE EXCEPTION 'Referencia no encontrada'; END IF;
  INSERT INTO public.pos_producto_config(producto_id,codigo_barras,costo_unitario,actualizado_en)
  VALUES(p_producto_id,NULLIF(btrim(p_codigo_barras),''),p_costo,now())
  ON CONFLICT(producto_id) DO UPDATE SET codigo_barras=EXCLUDED.codigo_barras,costo_unitario=EXCLUDED.costo_unitario,actualizado_en=now();
  RETURN jsonb_build_object('producto_id',p_producto_id,'guardado',true);
END $$;

CREATE OR REPLACE FUNCTION public.pos_importar_precios_clase(p_precios jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_row jsonb; v_producto_id bigint; v_ref text; v_nivel text; v_valor numeric; v_actualizados integer:=0; v_no_encontrados integer:=0;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_precios IS NULL OR jsonb_typeof(p_precios)<>'array' THEN RAISE EXCEPTION 'El archivo no tiene filas válidas'; END IF;
  FOR v_row IN SELECT value FROM jsonb_array_elements(p_precios) LOOP
    v_ref:=NULLIF(btrim(COALESCE(v_row->>'referencia',v_row->>'REF',v_row->>'Ref')),'');
    IF v_ref IS NULL THEN CONTINUE; END IF;
    SELECT id INTO v_producto_id FROM public.productos WHERE btrim(referencia::text)=v_ref AND COALESCE(eliminado,false)=false LIMIT 1;
    IF v_producto_id IS NULL THEN v_no_encontrados:=v_no_encontrados+1; CONTINUE; END IF;
    FOREACH v_nivel IN ARRAY ARRAY['A','B','C','D','E'] LOOP
      v_valor:=CASE WHEN NULLIF(btrim(COALESCE(v_row->>v_nivel,'')),'') IS NULL THEN NULL ELSE NULLIF(regexp_replace(v_row->>v_nivel,'[^0-9,.-]','','g'),'')::numeric END;
      IF v_valor<0 THEN RAISE EXCEPTION 'Precio inválido para referencia %, categoría %',v_ref,v_nivel; END IF;
      INSERT INTO public.pos_producto_precios_clase(producto_id,nivel,precio_unitario,actualizado_en)
      VALUES(v_producto_id,v_nivel,v_valor,now())
      ON CONFLICT(producto_id,nivel) DO UPDATE SET precio_unitario=EXCLUDED.precio_unitario,actualizado_en=now();
      IF v_valor IS NOT NULL THEN v_actualizados:=v_actualizados+1; END IF;
    END LOOP;
    v_producto_id:=NULL;
  END LOOP;
  RETURN jsonb_build_object('precios_importados',v_actualizados,'referencias_no_encontradas',v_no_encontrados);
END $$;

CREATE OR REPLACE FUNCTION public.pos_existencia(p_producto_id bigint)
RETURNS integer LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_stock integer;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  SELECT COALESCE(sum(cantidad),0)::integer INTO v_stock FROM public.pos_movimientos_inventario WHERE producto_id=p_producto_id;
  RETURN v_stock;
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_entrada(p_producto_id bigint, p_cantidad integer, p_nota text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_ref text;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_cantidad IS NULL OR p_cantidad <= 0 THEN RAISE EXCEPTION 'La cantidad debe ser mayor que cero'; END IF;
  SELECT referencia INTO v_ref FROM public.productos WHERE id=p_producto_id AND COALESCE(eliminado,false)=false FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Referencia no encontrada'; END IF;
  INSERT INTO public.pos_movimientos_inventario(producto_id,tipo,cantidad,nota) VALUES(p_producto_id,'entrada',p_cantidad,NULLIF(btrim(p_nota),''));
  RETURN jsonb_build_object('referencia',v_ref,'existencia',public.pos_existencia(p_producto_id));
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_venta(p_items jsonb, p_pagos jsonb, p_cliente jsonb DEFAULT '{}'::jsonb, p_nivel_precio text DEFAULT NULL, p_observacion text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_venta_id bigint; v_total numeric(14,2):=0; v_pagado numeric(14,2):=0; v_item jsonb; v_pago jsonb; v_producto record; v_cantidad integer; v_precio numeric(12,2); v_existencia integer;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_nivel_precio IS NOT NULL AND p_nivel_precio NOT IN ('A','B','C','D','E') THEN RAISE EXCEPTION 'Categoría de precio inválida'; END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)=0 THEN RAISE EXCEPTION 'Agrega al menos una referencia'; END IF;
  IF (SELECT count(*) FROM jsonb_array_elements(p_items)) <> (SELECT count(DISTINCT (x->>'producto_id')::bigint) FROM jsonb_array_elements(p_items) x) THEN RAISE EXCEPTION 'Cada referencia debe aparecer una sola vez en el carrito'; END IF;
  IF p_pagos IS NULL OR jsonb_typeof(p_pagos)<>'array' OR jsonb_array_length(p_pagos)=0 THEN RAISE EXCEPTION 'Registra al menos un pago'; END IF;
  -- Bloquea productos en orden estable para evitar ventas simultáneas con stock insuficiente.
  PERFORM 1 FROM public.productos p JOIN (SELECT DISTINCT (x->>'producto_id')::bigint id FROM jsonb_array_elements(p_items) x) i ON i.id=p.id ORDER BY p.id FOR UPDATE OF p;
  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    v_cantidad:=NULLIF(v_item->>'cantidad','')::integer; v_precio:=NULLIF(v_item->>'precio_unitario','')::numeric;
    IF v_cantidad IS NULL OR v_cantidad<=0 OR v_precio IS NULL OR v_precio<0 THEN RAISE EXCEPTION 'Cantidad o precio inválido'; END IF;
    SELECT p.id,p.referencia,p.nombre,COALESCE(c.costo_unitario,0) costo_unitario,COALESCE(p.eliminado,false) eliminado INTO v_producto FROM public.productos p LEFT JOIN public.pos_producto_config c ON c.producto_id=p.id WHERE p.id=(v_item->>'producto_id')::bigint;
    IF NOT FOUND OR v_producto.eliminado THEN RAISE EXCEPTION 'Una referencia ya no está disponible'; END IF;
    v_existencia:=public.pos_existencia(v_producto.id);
    IF v_existencia<v_cantidad THEN RAISE EXCEPTION 'Stock insuficiente para %, disponible: %',v_producto.referencia,v_existencia; END IF;
    v_total:=v_total+(v_cantidad*v_precio);
  END LOOP;
  FOR v_pago IN SELECT value FROM jsonb_array_elements(p_pagos) LOOP
    IF v_pago->>'medio' IS NULL OR v_pago->>'medio' NOT IN ('efectivo','transferencia','tarjeta','otro') OR COALESCE((v_pago->>'valor')::numeric,0)<=0 THEN RAISE EXCEPTION 'Revisa los medios y valores de pago'; END IF;
    IF v_pago->>'medio'='efectivo' AND COALESCE((v_pago->>'valor_recibido')::numeric,(v_pago->>'valor')::numeric)<(v_pago->>'valor')::numeric THEN RAISE EXCEPTION 'El efectivo recibido no puede ser menor al valor aplicado'; END IF;
    IF v_pago->>'medio'='transferencia' AND NULLIF(btrim(COALESCE(v_pago->>'referencia_pago','')),'') IS NULL THEN RAISE EXCEPTION 'Cada transferencia necesita su número de referencia'; END IF;
    v_pagado:=v_pagado+(v_pago->>'valor')::numeric;
  END LOOP;
  IF round(v_pagado,2)<>round(v_total,2) THEN RAISE EXCEPTION 'Los pagos deben sumar exactamente el total de la venta'; END IF;
  INSERT INTO public.pos_ventas(cliente_nombre,cliente_documento,cliente_telefono,cliente_ciudad,nivel_precio,subtotal,total,observacion)
  VALUES(NULLIF(btrim(p_cliente->>'nombre'),''),NULLIF(btrim(p_cliente->>'documento'),''),NULLIF(btrim(p_cliente->>'telefono'),''),NULLIF(btrim(p_cliente->>'ciudad'),''),p_nivel_precio,v_total,v_total,NULLIF(btrim(p_observacion),'')) RETURNING id INTO v_venta_id;
  UPDATE public.pos_ventas SET numero='V-'||to_char(now(),'YYYY')||'-'||lpad(v_venta_id::text,6,'0') WHERE id=v_venta_id;
  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    v_cantidad:=(v_item->>'cantidad')::integer; v_precio:=(v_item->>'precio_unitario')::numeric;
    SELECT p.id,p.referencia,p.nombre,COALESCE(c.costo_unitario,0) costo_unitario INTO v_producto FROM public.productos p LEFT JOIN public.pos_producto_config c ON c.producto_id=p.id WHERE p.id=(v_item->>'producto_id')::bigint;
    INSERT INTO public.pos_venta_items(venta_id,producto_id,referencia,nombre,cantidad,precio_unitario,costo_unitario)
    VALUES(v_venta_id,v_producto.id,v_producto.referencia,v_producto.nombre,v_cantidad,v_precio,COALESCE(v_producto.costo_unitario,0));
    INSERT INTO public.pos_movimientos_inventario(producto_id,tipo,cantidad,venta_id,nota)
    VALUES(v_producto.id,'venta',-v_cantidad,v_venta_id,'Venta '||v_venta_id);
  END LOOP;
  FOR v_pago IN SELECT value FROM jsonb_array_elements(p_pagos) LOOP
    INSERT INTO public.pos_pagos(venta_id,medio,valor,valor_recibido,cambio,banco,referencia_pago)
    VALUES(v_venta_id,v_pago->>'medio',(v_pago->>'valor')::numeric,CASE WHEN v_pago->>'medio'='efectivo' THEN COALESCE((v_pago->>'valor_recibido')::numeric,(v_pago->>'valor')::numeric) ELSE NULL END,CASE WHEN v_pago->>'medio'='efectivo' THEN GREATEST(COALESCE((v_pago->>'valor_recibido')::numeric,(v_pago->>'valor')::numeric)-(v_pago->>'valor')::numeric,0) ELSE 0 END,NULLIF(btrim(v_pago->>'banco'),''),NULLIF(btrim(v_pago->>'referencia_pago'),''));
  END LOOP;
  RETURN jsonb_build_object('id',v_venta_id,'numero',(SELECT numero FROM public.pos_ventas WHERE id=v_venta_id),'total',v_total);
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_devolucion(p_venta_id bigint, p_items jsonb, p_motivo text, p_nota text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_devolucion_id bigint; v_item jsonb; v_cantidad integer; v_vendido integer; v_devuelto integer; v_linea record; v_total numeric(14,2):=0; v_estado text;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF NULLIF(btrim(p_motivo),'') IS NULL OR jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)=0 THEN RAISE EXCEPTION 'Indica el motivo y las referencias devueltas'; END IF;
  PERFORM 1 FROM public.pos_ventas WHERE id=p_venta_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Venta no encontrada'; END IF;
  INSERT INTO public.pos_devoluciones(venta_id,valor,motivo,nota) VALUES(p_venta_id,0,btrim(p_motivo),NULLIF(btrim(p_nota),'')) RETURNING id INTO v_devolucion_id;
  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    v_cantidad:=(v_item->>'cantidad')::integer;
    IF v_cantidad<=0 THEN RAISE EXCEPTION 'Cantidad devuelta inválida'; END IF;
    SELECT id,cantidad,precio_unitario,producto_id INTO v_linea FROM public.pos_venta_items WHERE id=(v_item->>'venta_item_id')::bigint AND venta_id=p_venta_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'El artículo no pertenece a esta venta'; END IF;
    SELECT COALESCE(sum(di.cantidad),0)::integer INTO v_devuelto FROM public.pos_devolucion_items di JOIN public.pos_devoluciones d ON d.id=di.devolucion_id WHERE d.venta_id=p_venta_id AND di.venta_item_id=v_linea.id;
    v_vendido:=v_linea.cantidad-v_devuelto;
    IF v_cantidad>v_vendido THEN RAISE EXCEPTION 'La cantidad supera las unidades pendientes de devolución'; END IF;
    INSERT INTO public.pos_devolucion_items(devolucion_id,venta_item_id,cantidad,reintegrar_inventario,valor_linea)
    VALUES(v_devolucion_id,v_linea.id,v_cantidad,COALESCE((v_item->>'reintegrar_inventario')::boolean,false),v_cantidad*v_linea.precio_unitario);
    IF COALESCE((v_item->>'reintegrar_inventario')::boolean,false) THEN
      INSERT INTO public.pos_movimientos_inventario(producto_id,tipo,cantidad,venta_id,nota) VALUES(v_linea.producto_id,'devolucion',v_cantidad,p_venta_id,'Devolución '||v_devolucion_id);
    END IF;
    v_total:=v_total+(v_cantidad*v_linea.precio_unitario);
  END LOOP;
  UPDATE public.pos_devoluciones SET valor=v_total WHERE id=v_devolucion_id;
  SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM public.pos_venta_items vi WHERE vi.venta_id=p_venta_id AND vi.cantidad>COALESCE((SELECT sum(di.cantidad) FROM public.pos_devolucion_items di JOIN public.pos_devoluciones d ON d.id=di.devolucion_id WHERE d.venta_id=p_venta_id AND di.venta_item_id=vi.id),0)) THEN 'devuelta' ELSE 'devuelta_parcial' END INTO v_estado;
  UPDATE public.pos_ventas SET estado=v_estado WHERE id=p_venta_id;
  RETURN jsonb_build_object('devolucion_id',v_devolucion_id,'valor',v_total,'estado',v_estado);
END $$;

