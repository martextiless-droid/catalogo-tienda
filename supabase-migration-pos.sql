-- Datos internos de POS en tabla privada: el costo y el código no quedan
-- expuestos por los permisos de lectura pública del catálogo.
CREATE TABLE IF NOT EXISTS public.pos_producto_config (
  producto_id bigint PRIMARY KEY REFERENCES public.productos(id),
  codigo_barras text,
  costo_unitario numeric(12,2) NOT NULL DEFAULT 0 CHECK (costo_unitario >= 0),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS pos_producto_codigo_barras_unico
  ON public.pos_producto_config (codigo_barras)
  WHERE codigo_barras IS NOT NULL AND btrim(codigo_barras) <> '';

-- Tarifas mayoristas según la categoría del cliente definida en la pestaña BD.
CREATE TABLE IF NOT EXISTS public.pos_producto_precios_clase (
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  nivel text NOT NULL CHECK (nivel IN ('A','B','C','D','E')),
  precio_unitario numeric(12,2) CHECK (precio_unitario >= 0),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (producto_id,nivel)
);
ALTER TABLE public.pos_producto_precios_clase ALTER COLUMN precio_unitario DROP NOT NULL;

CREATE TABLE IF NOT EXISTS public.pos_ventas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero text UNIQUE,
  estado text NOT NULL DEFAULT 'completada' CHECK (estado IN ('completada','devuelta_parcial','devuelta','anulada')),
  cliente_nombre text,
  cliente_documento text,
  cliente_telefono text,
  cliente_ciudad text,
  nivel_precio text CHECK (nivel_precio IS NULL OR nivel_precio IN ('A','B','C','D','E')),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0),
  total numeric(14,2) NOT NULL CHECK (total >= 0),
  observacion text,
  vendedor uuid NOT NULL DEFAULT auth.uid(),
  creada_en timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.pos_ventas ADD COLUMN IF NOT EXISTS nivel_precio text;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='pos_ventas_nivel_precio_check') THEN
    ALTER TABLE public.pos_ventas ADD CONSTRAINT pos_ventas_nivel_precio_check CHECK (nivel_precio IS NULL OR nivel_precio IN ('A','B','C','D','E'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.pos_venta_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id bigint NOT NULL REFERENCES public.pos_ventas(id),
  producto_id bigint NOT NULL REFERENCES public.productos(id),
  referencia text NOT NULL,
  nombre text NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(12,2) NOT NULL CHECK (precio_unitario >= 0),
  costo_unitario numeric(12,2) NOT NULL DEFAULT 0 CHECK (costo_unitario >= 0),
  total_linea numeric(14,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED
);

CREATE TABLE IF NOT EXISTS public.pos_pagos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id bigint NOT NULL REFERENCES public.pos_ventas(id),
  medio text NOT NULL CHECK (medio IN ('efectivo','transferencia','tarjeta','otro')),
  valor numeric(14,2) NOT NULL CHECK (valor > 0),
  valor_recibido numeric(14,2),
  cambio numeric(14,2) NOT NULL DEFAULT 0 CHECK (cambio >= 0),
  banco text,
  referencia_pago text,
  registrado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pos_movimientos_inventario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id bigint NOT NULL REFERENCES public.productos(id),
  tipo text NOT NULL CHECK (tipo IN ('entrada','venta','devolucion','ajuste')),
  cantidad integer NOT NULL CHECK (cantidad <> 0),
  venta_id bigint REFERENCES public.pos_ventas(id),
  nota text,
  usuario uuid NOT NULL DEFAULT auth.uid(),
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pos_movimientos_producto_fecha
  ON public.pos_movimientos_inventario(producto_id, creado_en DESC);
CREATE INDEX IF NOT EXISTS pos_ventas_fecha ON public.pos_ventas(creada_en DESC);
CREATE INDEX IF NOT EXISTS pos_ventas_cliente ON public.pos_ventas(cliente_documento, creada_en DESC);
CREATE INDEX IF NOT EXISTS pos_items_referencia ON public.pos_venta_items(referencia);

CREATE TABLE IF NOT EXISTS public.pos_devoluciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id bigint NOT NULL REFERENCES public.pos_ventas(id),
  valor numeric(14,2) NOT NULL CHECK (valor >= 0),
  motivo text NOT NULL,
  nota text,
  registrado_por uuid NOT NULL DEFAULT auth.uid(),
  creada_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.pos_devolucion_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  devolucion_id bigint NOT NULL REFERENCES public.pos_devoluciones(id),
  venta_item_id bigint NOT NULL REFERENCES public.pos_venta_items(id),
  cantidad integer NOT NULL CHECK (cantidad > 0),
  reintegrar_inventario boolean NOT NULL DEFAULT false,
  valor_linea numeric(14,2) NOT NULL CHECK (valor_linea >= 0)
);

