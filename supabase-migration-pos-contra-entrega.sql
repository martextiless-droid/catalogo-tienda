-- Contra entrega con envío pagado por anticipado y registro posterior del recaudo.
-- Ejecutar una sola vez en Supabase SQL Editor después de las migraciones del POS.
BEGIN;

ALTER TABLE public.pos_pagos DROP CONSTRAINT IF EXISTS pos_pagos_medio_check;
ALTER TABLE public.pos_pagos ADD CONSTRAINT pos_pagos_medio_check
  CHECK (medio IN ('efectivo','transferencia','tarjeta','otro','saldo_favor','contra_entrega'));

ALTER TABLE public.pos_ventas ADD COLUMN IF NOT EXISTS envio_cobrado numeric(14,2) NOT NULL DEFAULT 0 CHECK(envio_cobrado>=0);
ALTER TABLE public.pos_ventas ADD COLUMN IF NOT EXISTS envio_medio text;
ALTER TABLE public.pos_ventas ADD COLUMN IF NOT EXISTS envio_banco text;
ALTER TABLE public.pos_ventas ADD COLUMN IF NOT EXISTS envio_referencia text;
ALTER TABLE public.pos_ventas DROP CONSTRAINT IF EXISTS pos_ventas_envio_medio_check;
ALTER TABLE public.pos_ventas ADD CONSTRAINT pos_ventas_envio_medio_check
  CHECK (envio_medio IS NULL OR envio_medio IN ('efectivo','transferencia','tarjeta','otro'));

CREATE TABLE IF NOT EXISTS public.pos_recaudos_contra_entrega (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id bigint NOT NULL REFERENCES public.pos_ventas(id),
  monto numeric(14,2) NOT NULL CHECK(monto>0),
  medio text NOT NULL CHECK(medio IN ('efectivo','transferencia')),
  banco text,
  referencia text,
  registrado_por uuid NOT NULL DEFAULT auth.uid(),
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (medio<>'transferencia' OR (NULLIF(btrim(banco),'') IS NOT NULL AND NULLIF(btrim(referencia),'') IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS pos_recaudos_contra_entrega_venta_idx ON public.pos_recaudos_contra_entrega(venta_id,creado_en);
ALTER TABLE public.pos_recaudos_contra_entrega ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pos_recaudos_contra_entrega FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.pos_recaudos_contra_entrega TO authenticated;
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='pos_recaudos_contra_entrega' AND policyname='POS admin lectura recaudos contra entrega') THEN
    EXECUTE 'CREATE POLICY "POS admin lectura recaudos contra entrega" ON public.pos_recaudos_contra_entrega FOR SELECT TO authenticated USING ((SELECT auth.uid()) = ''c1fd6ad7-15be-42a6-b239-0564bb34cba5''::uuid)';
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_venta_detallada(
  p_items jsonb, p_pagos jsonb, p_cliente jsonb DEFAULT '{}'::jsonb,
  p_nivel_precio text DEFAULT NULL, p_observacion text DEFAULT NULL,
  p_entrega jsonb DEFAULT '{}'::jsonb
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_result jsonb; v_id bigint; v_tipo text; v_transportadora text;
  v_pagos jsonb:=COALESCE(p_pagos,'[]'::jsonb); v_cliente_id bigint;
  v_doc text; v_tel text; v_total numeric(14,2); v_pagado numeric(14,2);
  v_credito numeric(14,2); v_aplicado numeric(14,2); v_envio numeric(14,2);
  v_envio_medio text; v_caja_id bigint; v_cod numeric(14,2);
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  v_tipo:=COALESCE(NULLIF(p_entrega->>'tipo',''),'recoge_cliente');
  v_transportadora:=NULLIF(btrim(p_entrega->>'transportadora'),'');
  IF v_tipo NOT IN ('recoge_cliente','transportadora','domicilio') THEN RAISE EXCEPTION 'Tipo de entrega inválido'; END IF;
  IF v_tipo='transportadora' AND v_transportadora IS NULL THEN RAISE EXCEPTION 'Selecciona la transportadora'; END IF;
  v_envio:=COALESCE(NULLIF(p_entrega->>'envio_valor','')::numeric,0);
  v_envio_medio:=NULLIF(p_entrega->>'envio_medio','');
  IF v_envio<0 THEN RAISE EXCEPTION 'El valor del envío no puede ser negativo'; END IF;
  IF v_envio>0 AND (v_envio_medio IS NULL OR v_envio_medio NOT IN ('efectivo','transferencia','tarjeta','otro')) THEN RAISE EXCEPTION 'Selecciona cómo se pagó el envío'; END IF;
  IF v_envio>0 AND v_envio_medio='transferencia' AND (NULLIF(btrim(p_entrega->>'envio_banco'),'') IS NULL OR NULLIF(btrim(p_entrega->>'envio_referencia'),'') IS NULL) THEN RAISE EXCEPTION 'El pago del envío por transferencia necesita banco y comprobante'; END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(v_pagos) x WHERE x->>'medio'='contra_entrega') AND v_tipo<>'transportadora' THEN RAISE EXCEPTION 'El pago contra entrega requiere una transportadora'; END IF;
  SELECT COALESCE(sum((x->>'cantidad')::numeric*(x->>'precio_unitario')::numeric),0) INTO v_total FROM jsonb_array_elements(COALESCE(p_items,'[]'::jsonb)) x;
  SELECT COALESCE(sum((x->>'valor')::numeric),0),COALESCE(sum((x->>'valor')::numeric) FILTER(WHERE x->>'medio'='contra_entrega'),0)
    INTO v_pagado,v_cod FROM jsonb_array_elements(v_pagos) x;
  v_doc:=NULLIF(regexp_replace(COALESCE(p_cliente->>'documento',''),'[^0-9]','','g'),'');
  v_tel:=NULLIF(regexp_replace(COALESCE(p_cliente->>'telefono',''),'[^0-9]','','g'),'');
  IF length(v_tel)=12 AND left(v_tel,2)='57' THEN v_tel:=substr(v_tel,3); END IF;
  SELECT id INTO v_cliente_id FROM public.pos_clientes c
  WHERE (v_doc IS NOT NULL AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc)
     OR (v_doc IS NULL AND v_tel IS NOT NULL AND regexp_replace(COALESCE(c.telefono,''),'[^0-9]','','g') IN (v_tel,'57'||v_tel))
  ORDER BY CASE WHEN v_doc IS NOT NULL AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_doc THEN 0 ELSE 1 END,c.actualizado_en DESC LIMIT 1 FOR UPDATE;
  IF v_cliente_id IS NOT NULL THEN
    SELECT COALESCE(sum(CASE WHEN tipo='abono' THEN monto WHEN tipo='uso_abono' THEN -monto ELSE 0 END),0)
      INTO v_credito FROM public.pos_movimientos_cuenta_cliente WHERE cliente_id=v_cliente_id;
  ELSE v_credito:=0; END IF;
  v_aplicado:=LEAST(GREATEST(v_total-v_pagado,0),GREATEST(v_credito,0));
  -- La función original acepta 'otro'; se usa temporalmente para guardar el nuevo medio sin reescribir el control de inventario.
  SELECT COALESCE(jsonb_agg(CASE WHEN x->>'medio'='contra_entrega'
    THEN jsonb_set(jsonb_set(x,'{medio}','"otro"'::jsonb),'{referencia_pago}','"__POS_CONTRA_ENTREGA__"'::jsonb,true)
    ELSE x END),'[]'::jsonb) INTO v_pagos FROM jsonb_array_elements(v_pagos) x;
  IF v_aplicado>0 THEN v_pagos:=v_pagos||jsonb_build_array(jsonb_build_object('medio','otro','valor',v_aplicado,'referencia_pago','__POS_SALDO_FAVOR__')); END IF;
  v_result:=public.pos_registrar_venta(p_items,v_pagos,p_cliente,p_nivel_precio,p_observacion);
  v_id:=(v_result->>'id')::bigint;
  UPDATE public.pos_pagos SET medio='contra_entrega',referencia_pago=NULL,banco=NULL
    WHERE venta_id=v_id AND medio='otro' AND referencia_pago='__POS_CONTRA_ENTREGA__';
  IF v_aplicado>0 AND v_cliente_id IS NOT NULL THEN
    UPDATE public.pos_pagos SET medio='saldo_favor',referencia_pago=NULL WHERE venta_id=v_id AND medio='otro' AND referencia_pago='__POS_SALDO_FAVOR__';
    INSERT INTO public.pos_movimientos_cuenta_cliente(cliente_id,tipo,monto,venta_id,nota) VALUES(v_cliente_id,'uso_abono',v_aplicado,v_id,'Aplicado a venta '||v_id);
  END IF;
  UPDATE public.pos_ventas SET
    barrio=COALESCE(NULLIF(btrim(p_cliente->>'barrio'),''),barrio),
    direccion=COALESCE(NULLIF(btrim(p_cliente->>'direccion'),''),direccion),
    tipo_entrega=v_tipo, transportadora=CASE WHEN v_tipo='transportadora' THEN v_transportadora ELSE NULL END,
    numero_guia=CASE WHEN v_tipo='transportadora' THEN NULLIF(btrim(p_entrega->>'guia'),'') ELSE NULL END,
    envio_cobrado=v_envio,envio_medio=CASE WHEN v_envio>0 THEN v_envio_medio ELSE NULL END,
    envio_banco=CASE WHEN v_envio_medio='transferencia' THEN NULLIF(btrim(p_entrega->>'envio_banco'),'') ELSE NULL END,
    envio_referencia=CASE WHEN v_envio_medio='transferencia' THEN NULLIF(btrim(p_entrega->>'envio_referencia'),'') ELSE NULL END,
    total=total+v_envio
  WHERE id=v_id;
  UPDATE public.pos_clientes SET barrio=COALESCE(NULLIF(btrim(p_cliente->>'barrio'),''),barrio),
    direccion=COALESCE(NULLIF(btrim(p_cliente->>'direccion'),''),direccion),actualizado_en=now()
  WHERE id=(SELECT cliente_id FROM public.pos_ventas WHERE id=v_id);
  IF v_envio>0 AND v_envio_medio='efectivo' THEN
    SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
    IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja para registrar el efectivo recibido por el envío'; END IF;
    INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,venta_id,nota)
      VALUES(v_caja_id,'venta','ingreso',v_envio,v_id,'Envío cobrado por anticipado · venta '||COALESCE(v_result->>'numero',v_id::text));
  END IF;
  RETURN v_result||jsonb_build_object('total',v_total+v_envio,'subtotal',v_total,'envio_cobrado',v_envio,'saldo_aplicado',v_aplicado,'saldo_favor_restante',GREATEST(v_credito-v_aplicado,0));
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_recaudo_contra_entrega(
  p_venta_id bigint,p_monto numeric,p_medio text,p_banco text DEFAULT NULL,p_referencia text DEFAULT NULL
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_estado text;v_numero text;v_pendiente numeric(14,2);v_caja_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_monto IS NULL OR p_monto<=0 OR p_medio NOT IN ('efectivo','transferencia') THEN RAISE EXCEPTION 'Indica un valor y medio de recaudo válidos'; END IF;
  IF p_medio='transferencia' AND (NULLIF(btrim(p_banco),'') IS NULL OR NULLIF(btrim(p_referencia),'') IS NULL) THEN RAISE EXCEPTION 'La transferencia necesita banco y comprobante'; END IF;
  SELECT estado,numero INTO v_estado,v_numero FROM public.pos_ventas WHERE id=p_venta_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Venta no encontrada'; END IF;
  IF v_estado<>'completada' THEN RAISE EXCEPTION 'Solo se reciben recaudos de ventas completadas'; END IF;
  SELECT COALESCE(sum(valor),0)-COALESCE((SELECT sum(monto) FROM public.pos_recaudos_contra_entrega WHERE venta_id=p_venta_id),0)
    INTO v_pendiente FROM public.pos_pagos WHERE venta_id=p_venta_id AND medio='contra_entrega';
  IF v_pendiente<=0 THEN RAISE EXCEPTION 'Esta venta no tiene recaudo contra entrega pendiente'; END IF;
  IF p_monto>v_pendiente THEN RAISE EXCEPTION 'El recaudo supera el saldo pendiente de %',v_pendiente; END IF;
  IF p_medio='efectivo' THEN
    SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
    IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja antes de registrar el efectivo de la transportadora'; END IF;
  END IF;
  INSERT INTO public.pos_recaudos_contra_entrega(venta_id,monto,medio,banco,referencia)
    VALUES(p_venta_id,p_monto,p_medio,CASE WHEN p_medio='transferencia' THEN btrim(p_banco) ELSE NULL END,CASE WHEN p_medio='transferencia' THEN btrim(p_referencia) ELSE NULL END);
  IF p_medio='efectivo' THEN
    INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,venta_id,nota)
      VALUES(v_caja_id,'venta','ingreso',p_monto,p_venta_id,'Recaudo contra entrega · venta '||COALESCE(v_numero,p_venta_id::text));
  END IF;
  RETURN jsonb_build_object('venta_id',p_venta_id,'recaudado',p_monto,'pendiente',v_pendiente-p_monto,'medio',p_medio);
END $$;

-- Al anular, también contempla el efectivo que ya hubiera entregado la transportadora.
CREATE OR REPLACE FUNCTION public.pos_anular_venta(p_venta_id bigint,p_motivo text,p_nota text DEFAULT NULL,p_reintegrar_inventario boolean DEFAULT true,p_reembolsar_efectivo boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_estado text;v_numero text;v_cliente_id bigint;v_efectivo numeric(14,2):=0;v_saldo_favor numeric(14,2):=0;v_caja_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF NULLIF(btrim(p_motivo),'') IS NULL THEN RAISE EXCEPTION 'Selecciona el motivo de anulación'; END IF;
  SELECT estado,numero,cliente_id INTO v_estado,v_numero,v_cliente_id FROM public.pos_ventas WHERE id=p_venta_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Venta no encontrada'; END IF;
  IF v_estado<>'completada' THEN RAISE EXCEPTION 'Solo se pueden anular ventas completadas sin devoluciones parciales'; END IF;
  IF EXISTS(SELECT 1 FROM public.pos_devoluciones WHERE venta_id=p_venta_id) THEN RAISE EXCEPTION 'Esta venta ya tiene devoluciones; no se puede anular completa'; END IF;
  SELECT COALESCE(sum(valor) FILTER(WHERE medio='efectivo'),0)+COALESCE((SELECT sum(monto) FROM public.pos_recaudos_contra_entrega WHERE venta_id=p_venta_id AND medio='efectivo'),0),
         COALESCE(sum(valor) FILTER(WHERE medio='saldo_favor'),0)
    INTO v_efectivo,v_saldo_favor FROM public.pos_pagos WHERE venta_id=p_venta_id;
  IF p_reembolsar_efectivo THEN
    IF v_efectivo<=0 THEN RAISE EXCEPTION 'Esta venta no tiene pagos en efectivo para reembolsar'; END IF;
    SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
    IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja para registrar el reembolso en efectivo'; END IF;
    IF v_efectivo>(SELECT saldo_inicial+COALESCE(sum(CASE WHEN direccion='ingreso' THEN monto ELSE -monto END),0) FROM public.pos_movimientos_caja WHERE caja_id=v_caja_id AND tipo<>'apertura') THEN RAISE EXCEPTION 'No hay efectivo suficiente en caja para registrar el reembolso'; END IF;
    INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,venta_id,nota) VALUES(v_caja_id,'retiro','egreso',v_efectivo,p_venta_id,'Reembolso por anulación de '||COALESCE(v_numero,p_venta_id::text));
  END IF;
  IF p_reintegrar_inventario THEN
    PERFORM 1 FROM public.productos p JOIN public.pos_venta_items vi ON vi.producto_id=p.id WHERE vi.venta_id=p_venta_id ORDER BY p.id FOR UPDATE OF p;
    INSERT INTO public.pos_movimientos_inventario(producto_id,variante_id,tipo,cantidad,venta_id,nota)
      SELECT producto_id,variante_id,'ajuste',cantidad,p_venta_id,'Reintegro por anulación de '||COALESCE(v_numero,p_venta_id::text) FROM public.pos_venta_items WHERE venta_id=p_venta_id;
  END IF;
  IF v_saldo_favor>0 AND v_cliente_id IS NOT NULL THEN
    INSERT INTO public.pos_movimientos_cuenta_cliente(cliente_id,tipo,monto,medio,venta_id,nota)
      VALUES(v_cliente_id,'abono',v_saldo_favor,'otro',p_venta_id,'Saldo a favor restaurado por anulación de '||COALESCE(v_numero,p_venta_id::text));
  END IF;
  UPDATE public.pos_ventas SET estado='anulada',anulada_en=now(),motivo_anulacion=btrim(p_motivo),nota_anulacion=NULLIF(btrim(p_nota),''),
    inventario_reintegrado=COALESCE(p_reintegrar_inventario,true),efectivo_reembolsado=CASE WHEN p_reembolsar_efectivo THEN v_efectivo ELSE 0 END WHERE id=p_venta_id;
  RETURN jsonb_build_object('id',p_venta_id,'numero',v_numero,'estado','anulada','inventario_reintegrado',COALESCE(p_reintegrar_inventario,true),
    'efectivo_reembolsado',CASE WHEN p_reembolsar_efectivo THEN v_efectivo ELSE 0 END,'saldo_favor_restaurado',v_saldo_favor);
END $$;

REVOKE ALL ON FUNCTION public.pos_registrar_venta_detallada(jsonb,jsonb,jsonb,text,text,jsonb),public.pos_registrar_recaudo_contra_entrega(bigint,numeric,text,text,text),public.pos_anular_venta(bigint,text,text,boolean,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.pos_registrar_venta_detallada(jsonb,jsonb,jsonb,text,text,jsonb),public.pos_registrar_recaudo_contra_entrega(bigint,numeric,text,text,text),public.pos_anular_venta(bigint,text,text,boolean,boolean) TO authenticated;
COMMIT;
