-- Categorías administrables para POS, administración y filtros del catálogo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.catalogo_categorias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  activa boolean NOT NULL DEFAULT true,
  orden integer NOT NULL DEFAULT 100,
  creada_en timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS catalogo_categorias_nombre_unico
  ON public.catalogo_categorias (translate(lower(btrim(nombre)),'áéíóúüñ','aeiouun'));

INSERT INTO public.catalogo_categorias(nombre,orden)
SELECT DISTINCT btrim(categoria),100
FROM public.productos
WHERE NULLIF(btrim(categoria),'') IS NOT NULL
ON CONFLICT DO NOTHING;
INSERT INTO public.catalogo_categorias(nombre,orden)
SELECT iniciales.nombre,iniciales.orden FROM (VALUES
  ('pijamas',10),('Niños',20),('Niñas',30),('Joggers',40),('Basicas',50)
) AS iniciales(nombre,orden)
WHERE NOT EXISTS (
  SELECT 1 FROM public.catalogo_categorias c
  WHERE translate(lower(btrim(c.nombre)),'áéíóúüñ','aeiouun')=translate(lower(iniciales.nombre),'áéíóúüñ','aeiouun')
)
ON CONFLICT DO NOTHING;

ALTER TABLE public.catalogo_categorias ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='catalogo_categorias' AND policyname='Lectura pública de categorías') THEN
    CREATE POLICY "Lectura pública de categorías" ON public.catalogo_categorias
      FOR SELECT TO anon,authenticated USING (activa);
  END IF;
END $$;
REVOKE ALL ON public.catalogo_categorias FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.catalogo_categorias TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.catalogo_crear_categoria(p_nombre text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_nombre text:=btrim(COALESCE(p_nombre,''));v_result jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF v_nombre='' OR length(v_nombre)>60 THEN RAISE EXCEPTION 'Escribe un nombre de categoría de 1 a 60 caracteres'; END IF;
  SELECT to_jsonb(c) INTO v_result FROM public.catalogo_categorias c
    WHERE translate(lower(btrim(c.nombre)),'áéíóúüñ','aeiouun')=translate(lower(v_nombre),'áéíóúüñ','aeiouun') LIMIT 1;
  IF v_result IS NOT NULL THEN RETURN v_result; END IF;
  INSERT INTO public.catalogo_categorias(nombre,orden) VALUES(v_nombre,100)
    ON CONFLICT DO NOTHING;
  SELECT to_jsonb(c) INTO v_result FROM public.catalogo_categorias c
    WHERE translate(lower(btrim(c.nombre)),'áéíóúüñ','aeiouun')=translate(lower(v_nombre),'áéíóúüñ','aeiouun') LIMIT 1;
  RETURN v_result;
END $$;
REVOKE ALL ON FUNCTION public.catalogo_crear_categoria(text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.catalogo_crear_categoria(text) TO authenticated;
COMMIT;
