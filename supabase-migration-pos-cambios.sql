-- Cambios de prendas en el POS: devuelve las prendas anteriores y registra
-- una venta enlazada para las nuevas dentro de la misma transacción.
-- Ejecutar después de las migraciones de inventario con variantes,
-- devoluciones, clientes/cuenta y ventas detalladas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pos_cambios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id uuid NOT NULL UNIQUE,
  venta_origen_id bigint NOT NULL REFERENCES public.pos_ventas(id),
  devolucion_id bigint NOT NULL UNIQUE REFERENCES public.pos_devoluciones(id),
  venta_nueva_id bigint NOT NULL UNIQUE REFERENCES public.pos_ventas(id),
  cliente_id bigint NOT NULL REFERENCES public.pos_clientes(id),
  valor_devuelto numeric(14,2) NOT NULL CHECK (valor_devuelto > 0),
  valor_nuevo numeric(14,2) NOT NULL CHECK (valor_nuevo > 0),
  diferencia numeric(14,2) NOT NULL,
  nota text,
  creado_en timestamptz NOT NULL DEFAULT now(),
  registrado_por uuid NOT NULL DEFAULT auth.uid()
);
CREATE INDEX IF NOT EXISTS pos_cambios_venta_origen_idx ON public.pos_cambios(venta_origen_id,creado_en DESC);
CREATE INDEX IF NOT EXISTS pos_cambios_venta_nueva_idx ON public.pos_cambios(venta_nueva_id);
ALTER TABLE public.pos_cambios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pos_cambios FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.pos_cambios TO authenticated;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='pos_cambios' AND policyname='POS admin lectura cambios') THEN
    CREATE POLICY "POS admin lectura cambios" ON public.pos_cambios
      FOR SELECT TO authenticated
      USING ((SELECT auth.uid())='c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid);
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.pos_registrar_cambio(
  p_venta_origen_id bigint,
  p_items_devolver jsonb,
  p_items_nuevos jsonb,
  p_pagos jsonb DEFAULT '[]'::jsonb,
  p_nota text DEFAULT NULL,
  p_solicitud_id uuid DEFAULT gen_random_uuid()
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_venta public.pos_ventas%ROWTYPE;
  v_cliente public.pos_clientes%ROWTYPE;
  v_items_devolver jsonb;
  v_cliente_json jsonb;
  v_venta_nueva jsonb;
  v_devolucion jsonb;
  v_cambio_id bigint;
  v_devolucion_id bigint;
  v_existing_new_sale_id bigint;
  v_cliente_id bigint;
  v_valor_devuelto numeric(14,2);
  v_valor_nuevo numeric(14,2);
  v_pago numeric(14,2);
  v_documento text;
  v_telefono text;
  v_nota text;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;
  IF p_solicitud_id IS NULL THEN RAISE EXCEPTION 'Identificador de solicitud inválido'; END IF;

  -- Evita repetir la operación si la respuesta se perdió y el POS la reintenta.
  SELECT id,venta_nueva_id,devolucion_id,valor_devuelto,valor_nuevo,diferencia
    INTO v_cambio_id,v_existing_new_sale_id,v_devolucion_id,v_valor_devuelto,v_valor_nuevo,v_pago
    FROM public.pos_cambios WHERE solicitud_id=p_solicitud_id;
  IF FOUND THEN
    RETURN jsonb_build_object('cambio_id',v_cambio_id,'venta_nueva_id',v_existing_new_sale_id,
      'devolucion_id',v_devolucion_id,'valor_devuelto',v_valor_devuelto,
      'valor_nuevo',v_valor_nuevo,'diferencia',v_pago,'repetido',true);
  END IF;

  SELECT * INTO v_venta FROM public.pos_ventas WHERE id=p_venta_origen_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Venta original no encontrada'; END IF;
  IF v_venta.estado NOT IN ('completada','devuelta_parcial') THEN
    RAISE EXCEPTION 'Solo se puede hacer un cambio desde una venta completada con unidades pendientes';
  END IF;
  IF jsonb_typeof(p_items_devolver)<>'array' OR jsonb_array_length(p_items_devolver)=0 THEN
    RAISE EXCEPTION 'Selecciona las prendas que recibes';
  END IF;
  IF jsonb_typeof(p_items_nuevos)<>'array' OR jsonb_array_length(p_items_nuevos)=0 THEN
    RAISE EXCEPTION 'Agrega las prendas nuevas del cambio';
  END IF;
  IF jsonb_typeof(COALESCE(p_pagos,'[]'::jsonb))<>'array' THEN RAISE EXCEPTION 'Revisa el pago de la diferencia'; END IF;

  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_items_devolver) x
    LEFT JOIN public.pos_venta_items vi
      ON vi.id=NULLIF(x->>'venta_item_id','')::bigint AND vi.venta_id=p_venta_origen_id
    WHERE vi.id IS NULL OR COALESCE(NULLIF(x->>'cantidad','')::integer,0)<=0
  ) THEN RAISE EXCEPTION 'Hay una prenda devuelta inválida o ajena a la venta'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_items_nuevos) x
    WHERE COALESCE(NULLIF(x->>'producto_id','')::bigint,0)<=0
       OR COALESCE(NULLIF(x->>'cantidad','')::integer,0)<=0
       OR COALESCE(NULLIF(x->>'precio_unitario','')::numeric,-1)<0
  ) THEN RAISE EXCEPTION 'Revisa las referencias, cantidades y precios de las prendas nuevas'; END IF;

  SELECT COALESCE(sum((x->>'cantidad')::numeric*vi.precio_unitario),0)
    INTO v_valor_devuelto
    FROM jsonb_array_elements(p_items_devolver) x
    JOIN public.pos_venta_items vi ON vi.id=(x->>'venta_item_id')::bigint AND vi.venta_id=p_venta_origen_id;
  SELECT COALESCE(sum((x->>'cantidad')::numeric*(x->>'precio_unitario')::numeric),0)
    INTO v_valor_nuevo FROM jsonb_array_elements(p_items_nuevos) x;
  SELECT COALESCE(sum((x->>'valor')::numeric),0)
    INTO v_pago FROM jsonb_array_elements(COALESCE(p_pagos,'[]'::jsonb)) x;

  IF v_valor_devuelto<=0 OR v_valor_nuevo<=0 THEN RAISE EXCEPTION 'Los valores del cambio deben ser mayores que cero'; END IF;
  IF round(v_pago,2)<>round(GREATEST(v_valor_nuevo-v_valor_devuelto,0),2) THEN
    RAISE EXCEPTION 'El pago debe ser exactamente la diferencia de %',GREATEST(v_valor_nuevo-v_valor_devuelto,0);
  END IF;

  v_cliente_id:=v_venta.cliente_id;
  v_documento:=NULLIF(regexp_replace(COALESCE(v_venta.cliente_documento,''),'[^0-9]','','g'),'');
  v_telefono:=NULLIF(regexp_replace(COALESCE(v_venta.cliente_telefono,''),'[^0-9]','','g'),'');
  IF length(v_telefono)=12 AND left(v_telefono,2)='57' THEN v_telefono:=substr(v_telefono,3); END IF;
  IF v_cliente_id IS NULL THEN
    SELECT id INTO v_cliente_id FROM public.pos_clientes c
    WHERE (v_documento IS NOT NULL AND regexp_replace(COALESCE(c.documento,''),'[^0-9]','','g')=v_documento)
       OR (v_documento IS NULL AND v_telefono IS NOT NULL AND regexp_replace(COALESCE(c.telefono,''),'[^0-9]','','g') IN (v_telefono,'57'||v_telefono))
    ORDER BY c.actualizado_en DESC LIMIT 1 FOR UPDATE;
  END IF;
  IF v_cliente_id IS NULL THEN
    RAISE EXCEPTION 'Esta venta no tiene un cliente identificable. Registra el documento o teléfono para guardar correctamente el saldo a favor del cambio';
  END IF;
  SELECT * INTO v_cliente FROM public.pos_clientes WHERE id=v_cliente_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró la cuenta del cliente de esta venta'; END IF;
  IF v_documento IS NULL THEN v_documento:=NULLIF(regexp_replace(COALESCE(v_cliente.documento,''),'[^0-9]','','g'),''); END IF;
  IF v_telefono IS NULL THEN v_telefono:=NULLIF(regexp_replace(COALESCE(v_cliente.telefono,''),'[^0-9]','','g'),''); END IF;
  IF v_documento IS NULL AND v_telefono IS NULL THEN
    RAISE EXCEPTION 'El cliente debe tener documento o teléfono para vincular el saldo del cambio a la nueva venta';
  END IF;

  v_cliente_json:=jsonb_build_object(
    'nombre',COALESCE(NULLIF(btrim(v_venta.cliente_nombre),''),v_cliente.nombre),
    'documento',COALESCE(v_documento,''),
    'telefono',COALESCE(v_telefono,''),
    'ciudad',COALESCE(NULLIF(btrim(v_venta.cliente_ciudad),''),v_cliente.ciudad),
    'barrio',COALESCE(NULLIF(btrim(v_venta.barrio),''),v_cliente.barrio),
    'direccion',COALESCE(NULLIF(btrim(v_venta.direccion),''),v_cliente.direccion),
    'nivel_precio',v_venta.nivel_precio
  );
  v_nota:=NULLIF(btrim(p_nota),'');

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
      'venta_item_id',(x->>'venta_item_id')::bigint,
      'cantidad',(x->>'cantidad')::integer,
      'reintegrar_inventario',true
    )),'[]'::jsonb)
    INTO v_items_devolver FROM jsonb_array_elements(p_items_devolver) x;
  v_devolucion:=public.pos_registrar_devolucion(
    p_venta_origen_id,v_items_devolver,'Cambio de talla o referencia',v_nota
  );

  -- El valor recibido se convierte en crédito temporal y la venta nueva lo usa
  -- automáticamente; la parte sobrante queda como saldo a favor del cliente.
  INSERT INTO public.pos_movimientos_cuenta_cliente(cliente_id,tipo,monto,venta_id,nota)
  VALUES(v_cliente_id,'abono',v_valor_devuelto,p_venta_origen_id,
    'Valor de prendas recibidas por cambio · Venta '||COALESCE(v_venta.numero,p_venta_origen_id::text));

  v_venta_nueva:=public.pos_registrar_venta_detallada(
    p_items_nuevos,COALESCE(p_pagos,'[]'::jsonb),v_cliente_json,v_venta.nivel_precio,
    'Cambio asociado a '||COALESCE(v_venta.numero,'Venta '||p_venta_origen_id::text)||COALESCE(' · '||v_nota,''),
    jsonb_build_object('tipo','recoge_cliente')
  );

  INSERT INTO public.pos_cambios(
    solicitud_id,venta_origen_id,devolucion_id,venta_nueva_id,cliente_id,
    valor_devuelto,valor_nuevo,diferencia,nota
  ) VALUES (
    p_solicitud_id,p_venta_origen_id,(v_devolucion->>'devolucion_id')::bigint,
    (v_venta_nueva->>'id')::bigint,v_cliente_id,v_valor_devuelto,v_valor_nuevo,
    v_valor_nuevo-v_valor_devuelto,v_nota
  ) RETURNING id INTO v_cambio_id;

  RETURN jsonb_build_object(
    'cambio_id',v_cambio_id,
    'devolucion_id',(v_devolucion->>'devolucion_id')::bigint,
    'venta_origen_id',p_venta_origen_id,
    'venta_nueva_id',(v_venta_nueva->>'id')::bigint,
    'venta_nueva_numero',v_venta_nueva->>'numero',
    'valor_devuelto',v_valor_devuelto,
    'valor_nuevo',v_valor_nuevo,
    'diferencia',v_valor_nuevo-v_valor_devuelto,
    'saldo_favor_restante',COALESCE((v_venta_nueva->>'saldo_favor_restante')::numeric,0)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.pos_registrar_cambio(bigint,jsonb,jsonb,jsonb,text,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.pos_registrar_cambio(bigint,jsonb,jsonb,jsonb,text,uuid) TO authenticated;

COMMIT;
