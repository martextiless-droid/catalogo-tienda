-- Registro de gastos pagados y trazabilidad para exportar movimientos del POS al contador.
-- Ejecutar una vez después de las migraciones base de ventas, caja e inventario.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pos_gastos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Bogota')::date,
  categoria text NOT NULL CHECK (categoria IN ('arriendo','nomina','servicios','transporte','empaques','comisiones','impuestos','mantenimiento','compras_menores','otro')),
  concepto text NOT NULL,
  tercero text,
  documento_tercero text,
  numero_soporte text,
  monto numeric(14,2) NOT NULL CHECK (monto>0),
  medio text NOT NULL CHECK (medio IN ('efectivo','transferencia','tarjeta','otro')),
  banco text,
  referencia_pago text,
  nota text,
  caja_movimiento_id bigint,
  registrado_por uuid NOT NULL DEFAULT auth.uid(),
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pos_gastos_fecha_idx ON public.pos_gastos(fecha DESC,id DESC);

ALTER TABLE public.pos_movimientos_caja
  ADD COLUMN IF NOT EXISTS gasto_id bigint REFERENCES public.pos_gastos(id);
CREATE UNIQUE INDEX IF NOT EXISTS pos_movimientos_caja_gasto_unico
  ON public.pos_movimientos_caja(gasto_id) WHERE gasto_id IS NOT NULL;
ALTER TABLE public.pos_gastos
  DROP CONSTRAINT IF EXISTS pos_gastos_caja_movimiento_fk;
ALTER TABLE public.pos_gastos
  ADD CONSTRAINT pos_gastos_caja_movimiento_fk
  FOREIGN KEY(caja_movimiento_id) REFERENCES public.pos_movimientos_caja(id);

ALTER TABLE public.pos_gastos ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='pos_gastos' AND policyname='POS admin lectura gastos') THEN
    CREATE POLICY "POS admin lectura gastos" ON public.pos_gastos FOR SELECT TO authenticated
      USING ((SELECT auth.uid())='c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid);
  END IF;
END $$;
REVOKE ALL ON public.pos_gastos FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.pos_gastos TO authenticated;

CREATE OR REPLACE FUNCTION public.pos_registrar_gasto(
  p_fecha date,
  p_categoria text,
  p_concepto text,
  p_monto numeric,
  p_medio text,
  p_tercero text DEFAULT NULL,
  p_documento_tercero text DEFAULT NULL,
  p_numero_soporte text DEFAULT NULL,
  p_banco text DEFAULT NULL,
  p_referencia_pago text DEFAULT NULL,
  p_nota text DEFAULT NULL
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_caja_id bigint; v_gasto_id bigint; v_movimiento_id bigint;
BEGIN
  IF auth.uid() IS DISTINCT FROM 'c1fd6ad7-15be-42a6-b239-0564bb34cba5'::uuid THEN RAISE EXCEPTION 'No autorizado'; END IF;
  IF p_fecha IS NULL OR p_categoria NOT IN ('arriendo','nomina','servicios','transporte','empaques','comisiones','impuestos','mantenimiento','compras_menores','otro') THEN RAISE EXCEPTION 'Revisa la fecha y la categoría del gasto'; END IF;
  IF NULLIF(btrim(p_concepto),'') IS NULL OR p_monto IS NULL OR p_monto<=0 THEN RAISE EXCEPTION 'Escribe el concepto y un valor mayor que cero'; END IF;
  IF p_medio NOT IN ('efectivo','transferencia','tarjeta','otro') THEN RAISE EXCEPTION 'Selecciona una forma de pago válida'; END IF;
  IF p_medio='transferencia' AND (NULLIF(btrim(p_banco),'') IS NULL OR NULLIF(btrim(p_referencia_pago),'') IS NULL) THEN RAISE EXCEPTION 'La transferencia necesita banco y comprobante'; END IF;
  IF p_medio='efectivo' THEN
    SELECT id INTO v_caja_id FROM public.pos_cajas WHERE estado='abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE;
    IF v_caja_id IS NULL THEN RAISE EXCEPTION 'Abre la caja para registrar un gasto pagado en efectivo'; END IF;
  END IF;

  INSERT INTO public.pos_gastos(fecha,categoria,concepto,tercero,documento_tercero,numero_soporte,monto,medio,banco,referencia_pago,nota)
  VALUES(p_fecha,p_categoria,btrim(p_concepto),NULLIF(btrim(p_tercero),''),NULLIF(btrim(p_documento_tercero),''),NULLIF(btrim(p_numero_soporte),''),p_monto,p_medio,
    CASE WHEN p_medio='transferencia' THEN NULLIF(btrim(p_banco),'') ELSE NULL END,
    CASE WHEN p_medio='transferencia' THEN NULLIF(btrim(p_referencia_pago),'') ELSE NULL END,
    NULLIF(btrim(p_nota),''))
  RETURNING id INTO v_gasto_id;

  IF p_medio='efectivo' THEN
    INSERT INTO public.pos_movimientos_caja(caja_id,tipo,direccion,monto,gasto_id,nota)
    VALUES(v_caja_id,'retiro','egreso',p_monto,v_gasto_id,'Gasto '||v_gasto_id||' · '||btrim(p_concepto))
    RETURNING id INTO v_movimiento_id;
    UPDATE public.pos_gastos SET caja_movimiento_id=v_movimiento_id WHERE id=v_gasto_id;
  END IF;

  RETURN jsonb_build_object('id',v_gasto_id,'fecha',p_fecha,'monto',p_monto,'medio',p_medio,'caja_movimiento_id',v_movimiento_id);
END;
$$;

REVOKE ALL ON FUNCTION public.pos_registrar_gasto(date,text,text,numeric,text,text,text,text,text,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.pos_registrar_gasto(date,text,text,numeric,text,text,text,text,text,text,text) TO authenticated;

COMMIT;
