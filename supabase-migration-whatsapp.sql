-- Base privada para conversaciones de WhatsApp y fotos diarias por referencia.
-- Ejecutar en Supabase SQL Editor antes de desplegar la función.
BEGIN;

CREATE TABLE IF NOT EXISTS public.whatsapp_contactos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telefono text NOT NULL UNIQUE,
  nombre text,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  ultimo_mensaje_en timestamptz
);

CREATE TABLE IF NOT EXISTS public.whatsapp_mensajes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contacto_id bigint NOT NULL REFERENCES public.whatsapp_contactos(id) ON DELETE CASCADE,
  direccion text NOT NULL CHECK (direccion IN ('entrante','saliente')),
  tipo text NOT NULL DEFAULT 'texto',
  texto text,
  id_mensaje_meta text UNIQUE,
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS whatsapp_mensajes_contacto_fecha
  ON public.whatsapp_mensajes(contacto_id, creado_en DESC);

CREATE TABLE IF NOT EXISTS public.whatsapp_fotos_referencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia text NOT NULL,
  url text NOT NULL,
  descripcion text,
  activa boolean NOT NULL DEFAULT true,
  tanda_id uuid NOT NULL DEFAULT gen_random_uuid(),
  creada_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS whatsapp_fotos_referencia_activas
  ON public.whatsapp_fotos_referencia(referencia, activa, creada_en DESC);

ALTER TABLE public.whatsapp_contactos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_mensajes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_fotos_referencia ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.whatsapp_contactos, public.whatsapp_mensajes,
  public.whatsapp_fotos_referencia FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_contactos_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_mensajes_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_fotos_referencia_id_seq TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.whatsapp_contactos,
  public.whatsapp_mensajes, public.whatsapp_fotos_referencia TO service_role;

COMMIT;
